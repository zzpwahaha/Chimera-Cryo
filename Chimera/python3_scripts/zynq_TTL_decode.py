import re
import numpy as np
import matplotlib.pyplot as plt


def parse_gpio_sequence(text):
    """
    Parse GPIO_seq_point lines and return times (ns) and TTL states (N x 64).
    """
    pattern = re.compile(
        r"time=\s*(\d+)\s*,outputA\s*=\s*(0x[0-9a-fA-F]+)\s*,outputB\s*=\s*(0x[0-9a-fA-F]+)"
    )

    times = []
    states = []

    for line in text.splitlines():
        m = pattern.search(line)
        if not m:
            continue

        t = int(m.group(1))*10          # ns
        outA = int(m.group(2), 16)
        outB = int(m.group(3), 16)

        bitsA = [(outA >> i) & 1 for i in range(32)]
        bitsB = [(outB >> i) & 1 for i in range(32)]

        times.append(t)
        states.append(bitsA + bitsB)

    return np.array(times), np.array(states)


def plot_ttl(times, states):
    """
    Plot 64-channel TTL timing diagram.
    """
    # Step-wise expansion (hold value until next timestamp)
    t_step = np.repeat(times, 2)[1:]
    s_step = np.repeat(states, 2, axis=0)[:-1]

    plt.figure(figsize=(10, 6))

    for ch in range(64):
        plt.step(
            t_step,
            s_step[:, ch] + ch,  # vertical offset per channel
            where="post"
        )

    plt.xlabel("Time (ns)")
    plt.ylabel("TTL Channel (offset)")
    plt.title("TTL Status vs Time")
    plt.tight_layout()
    plt.show()


